import { chromium } from "playwright";
const base = "http://localhost:4173";
const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
let fehler = 0;
const ok = (bed, t) => { console.log((bed ? "OK   " : "FEHLT") + " " + t); if (!bed) fehler++; };
const p = await (await b.newContext({ viewport: { width: 390, height: 844 }, locale: "de-DE" })).newPage();
const logs = []; p.on("pageerror", (e) => logs.push(e.message));
let skript = false; p.on("request", (r) => { if (r.url().includes("challenges.cloudflare.com")) skript = true; });
await p.goto(base + "/auth", { waitUntil: "networkidle" });
ok(!skript, "Ohne Schlüssel wird kein Cloudflare-Skript geladen");
await p.locator("#land").selectOption("NG");
ok(await p.getByText("Für dieses Land verschicken wir keine SMS-Codes.").isVisible(), "Nigeria: Hinweis statt SMS");
await p.locator("input[type=tel]").fill("8012345678");
await p.getByRole("button", { name: /Code senden|Code per SMS/ }).first().click();
await p.waitForTimeout(300);
ok(await p.getByText("Für dieses Land verschicken wir keine SMS. Bitte nutzen Sie E-Mail").first().isVisible(), "Kein SMS-Versand nach Nigeria");
await p.getByRole("button", { name: "Mit E-Mail fortfahren" }).click();
ok(await p.locator("input[name=email]").isVisible(), "Wechsel auf E-Mail");
await p.getByRole("button", { name: "Mit Handynummer" }).click();
await p.locator("#land").selectOption("RO");
ok(await p.getByText("Für dieses Land verschicken wir keine SMS-Codes.").count() === 0, "Rumänien: SMS erlaubt");
ok(logs.length === 0, "Keine Fehler" + (logs.length ? ": " + logs.join(" | ") : ""));
await b.close();
console.log(fehler ? `\n${fehler} Prüfung(en) fehlgeschlagen` : "\nAlle Prüfungen bestanden");
process.exit(fehler ? 1 : 0);
